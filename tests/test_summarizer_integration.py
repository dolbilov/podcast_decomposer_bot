import pytest

from podcast_decomposer_bot.nlp import summarizer

INPUT_TEXT = (
    "В современном мире технологии развиваются стремительными темпами, и каждый человек ежедневно "
    "пользуется достижениями науки и техники, будь то смартфон, компьютер или умный дом, однако одновременно "
    "с прогрессом возникают новые вызовы, связанные с безопасностью и этикой, поэтому важно сочетать "
    "инновации с ответственным отношением к рискам, чтобы обеспечить устойчивое развитие общества и "
    "комфортную жизнь будущим поколениям, а также уделять внимание вопросам конфиденциальности данных, "
    "экологической."
)


@pytest.mark.integration
def test_summarizer_integration_shortens_text():
    summary = summarizer.summarize(INPUT_TEXT, max_length=100)

    assert isinstance(summary, str), "Резюме должно быть строкой"
    assert summary.strip(), "Резюме не должно быть пустым"
    assert len(summary) < len(INPUT_TEXT), "Резюме должно быть короче исходного"
